void bc7() {
    for (const Bc7Golden& g : kBc7) {
        uint8_t out[64];
        decodeBlock(Kind::BC7, false, g.block, out);
        CHECK(std::memcmp(out, g.rgba, 64) == 0);
    }
    // Mode 6 by hand: one subset, RGBA 7 bits and a p-bit per endpoint, 4-bit indices (the anchor one bit short).
    // Index 0 of every texel except texel 1 (index 15): texel 0 is endpoint 0, texel 1 endpoint 1.
    BlockWriter w;
    w.put(1u << 6, 7);  // mode 6
    const unsigned e0[4] = {100, 20, 5, 127}, e1[4] = {0, 127, 64, 0};
    for (unsigned c = 0; c < 4; ++c) w.put(e0[c], 7), w.put(e1[c], 7);
    w.put(1, 1).put(0, 1);  // p-bits
    w.put(0, 3);            // texel 0 (anchor)
    w.put(15, 4);           // texel 1
    uint8_t out[64];
    decodeBlock(Kind::BC7, false, w.bytes, out);
    const unsigned px0[4] = {100 << 1 | 1, 20 << 1 | 1, 5 << 1 | 1, 127 << 1 | 1}, px1[4] = {0, 127 << 1, 64 << 1, 0};
    for (unsigned c = 0; c < 4; ++c) CHECK(out[c] == px0[c] && out[4 + c] == px1[c]);
    // A block whose leading byte has no set bit is a reserved mode: all zero, alpha too.
    const uint8_t reserved[16] = {};
    decodeBlock(Kind::BC7, false, reserved, out);
    uint8_t zeros[64] = {};
    CHECK(std::memcmp(out, zeros, 64) == 0);
}

