// Appends fields to a 128-bit block, least significant bit first.
struct BlockWriter {
    uint8_t bytes[16] = {};
    unsigned pos = 0;
    BlockWriter& put(uint32_t value, unsigned bits) {
        for (unsigned i = 0; i < bits; ++i, ++pos)
            if (value >> i & 1) bytes[pos / 8] |= uint8_t(1u << (pos % 8));
        return *this;
    }
};

float halfToFloat(uint16_t h) {
    const int e = h >> 10 & 31;
    const float m = float(h & 1023);
    const float v = e == 0 ? std::ldexp(m, -24) : std::ldexp(1024.0f + m, e - 25);
    return h & 0x8000 ? -v : v;
}
uint16_t half(const uint8_t* p) { return uint16_t(p[0] | p[1] << 8); }

void bc1() {
    // Four-colour mode (c0 > c1): red, blue and the two thirds between them.
    const uint8_t four[8] = {0x00, 0xF8, 0x1F, 0x00, 0xE4, 0xE4, 0xE4, 0xE4};
    uint8_t out[64];
    decodeBlock(Kind::BC1, false, four, out);
    const uint8_t expect[16] = {255, 0, 0, 255, 0, 0, 255, 255, 170, 0, 85, 255, 85, 0, 170, 255};
    CHECK(std::memcmp(out, expect, 16) == 0);
    CHECK(std::memcmp(out + 16, expect, 16) == 0);  // (every row has the same indices)
    // Three-colour mode (c0 <= c1): the midpoint, and index 3 is transparent black.
    const uint8_t three[8] = {0x1F, 0x00, 0x00, 0xF8, 0xE4, 0xE4, 0xE4, 0xE4};
    decodeBlock(Kind::BC1, false, three, out);
    const uint8_t expect3[16] = {0, 0, 255, 255, 255, 0, 0, 255, 127, 0, 127, 255, 0, 0, 0, 0};
    CHECK(std::memcmp(out, expect3, 16) == 0);
}

void bc2bc3() {
    // BC2: 4-bit alpha, the colour block is four-colour whatever the order of the endpoints.
    const uint8_t b2[16] = {0x10, 0x32, 0, 0, 0, 0, 0, 0, 0x00, 0xF8, 0x00, 0xF8, 0, 0, 0, 0};
    uint8_t out[64];
    decodeBlock(Kind::BC2, false, b2, out);
    CHECK(out[0] == 255 && out[1] == 0 && out[2] == 0 && out[3] == 0);
    CHECK(out[7] == 17 && out[11] == 34 && out[15] == 51 && out[19] == 0);
    // BC3: 8-bit alpha with interpolated values (255, 0, then 218 = 6/7 and 36 = 1/7 of the way).
    const uint8_t b3[16] = {255, 0, 0x88, 0x0E, 0, 0, 0, 0, 0x00, 0xF8, 0x00, 0xF8, 0, 0, 0, 0};
    decodeBlock(Kind::BC3, false, b3, out);
    CHECK(out[3] == 255 && out[7] == 0 && out[11] == 218 && out[15] == 36);
    CHECK(out[0] == 255 && out[1] == 0 && out[2] == 0);
}

void bc4bc5() {
    uint8_t out[128];
    // Six-value mode (r0 <= r1): 0, 255, then 51 = 1/5 of the way, and the explicit 0 (index 6) and 255 (index 7).
    const uint8_t unsigned6[8] = {0, 255, 0xF2, 0x01, 0, 0, 0, 0};  // texels 0..2: indices 2, 6, 7
    decodeBlock(Kind::BC4, false, unsigned6, out);
    CHECK(out[0] == 51 && out[1] == 0 && out[2] == 255 && out[3] == 0);
    // Eight-value mode.
    const uint8_t unsigned8[8] = {255, 0, 0x88, 0x0E, 0, 0, 0, 0};  // indices 0, 1, 2, 7
    decodeBlock(Kind::BC4, false, unsigned8, out);
    CHECK(out[0] == 255 && out[1] == 0 && out[2] == 218 && out[3] == 36);
    // Signed: endpoints 127 and -127 (0x81); -128 is read as -127.
    const uint8_t signed8[8] = {0x7F, 0x81, 0x88, 0x0E, 0, 0, 0, 0};
    decodeBlock(Kind::BC4, true, signed8, out);
    CHECK(out[0] == 0x7F && out[1] == 0x81 && out[2] == 90 && out[3] == uint8_t(int8_t(-90)));
    const uint8_t clamp[8] = {0x80, 0x80, 0, 0, 0, 0, 0, 0};
    decodeBlock(Kind::BC4, true, clamp, out);
    CHECK(out[0] == 0x81);
    // BC5: two BC4 blocks, red then green, interleaved.
    const uint8_t b5[16] = {200, 200, 0, 0, 0, 0, 0, 0, 100, 100, 0, 0, 0, 0, 0, 0};
    decodeBlock(Kind::BC5, false, b5, out);
    CHECK(out[0] == 200 && out[1] == 100 && out[30] == 200 && out[31] == 100);
    CHECK(texelBytes(Kind::BC4) == 1 && texelBytes(Kind::BC5) == 2 && texelBytes(Kind::BC6H) == 8 && texelBytes(Kind::BC7) == 4);
}

