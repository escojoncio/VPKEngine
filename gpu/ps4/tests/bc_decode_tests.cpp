void bc6h() {
    for (const Bc6Golden& g : kBc6) {
        uint8_t out[128];
        decodeBlock(Kind::BC6H, false, g.block, out);
        for (unsigned t = 0; t < 16; ++t) {
            CHECK(half(out + 8 * t + 6) == 0x3C00);  // alpha 1.0
            for (unsigned c = 0; c < 3; ++c) {
                const float f = std::fmin(std::fmax(halfToFloat(half(out + 8 * t + 2 * c)), 0.0f), 1.0f);
                CHECK(int(f * 255.0f) == g.rgb[3 * t + c]);
            }
        }
    }
    // Mode 11 (00011: one subset, 10-bit endpoints stored whole). RW = GW = BW = 512, everything else 0: every texel is
    // the first endpoint, unquantised ((512 << 15) + 0x4000) >> 9 = 32800 and finished (32800 * 31) >> 6 = 15887.
    BlockWriter w;
    w.put(3, 5);
    for (unsigned i = 0; i < 3; ++i) w.put(512, 10);
    uint8_t out[128];
    decodeBlock(Kind::BC6H, false, w.bytes, out);
    for (unsigned t = 0; t < 16; ++t)
        CHECK(half(out + 8 * t) == 15887 && half(out + 8 * t + 2) == 15887 && half(out + 8 * t + 4) == 15887);
    // The same signed: endpoint 0x3FF is -1, unquantised -96 and finished (96 * 31) >> 5 = 93 with the sign bit.
    BlockWriter s;
    s.put(3, 5);
    for (unsigned i = 0; i < 3; ++i) s.put(0x3FF, 10);
    decodeBlock(Kind::BC6H, true, s.bytes, out);
    for (unsigned t = 0; t < 16; ++t) CHECK(half(out + 8 * t) == 0x805D && half(out + 8 * t + 2) == 0x805D && half(out + 8 * t + 4) == 0x805D);
    // Mode 12 (00111: one subset, 11-bit base, 9-bit deltas), signed. Base (-16, 100, 1000) = (0x7F0, 100, 1000) in 11 bits,
    // deltas (+20, -30, +50) (-30 = 0x1E2 in 9 bits). Second endpoint: base + delta masked to 11 bits and sign extended:
    // (4, 70, 1050 -> 1050 - 2048 = -998). Unquantised ((v << 15) + 0x4000) >> 10 with the sign kept: (-528, 144), (3216, 2256),
    // (32016, -31952). Texel 0 uses index 0 (the first endpoint), texel 1 index 15 (the second); finished (v * 31) >> 5 of
    // the magnitude with the sign bit: R 0x81FF / 0x008B, G 0x0C2B / 0x0889, B 0x7927 / 0xF8E9.
    BlockWriter t12;
    t12.put(7, 5);
    t12.put(0x7F0 & 0x3FF, 10).put(100, 10).put(1000, 10);
    t12.put(20, 9).put(0x7F0 >> 10, 1).put(0x1E2, 9).put(100 >> 10, 1).put(50, 9).put(1000 >> 10, 1);
    t12.put(0, 3).put(15, 4);
    decodeBlock(Kind::BC6H, true, t12.bytes, out);
    CHECK(half(out) == 0x81FF && half(out + 2) == 0x0C2B && half(out + 4) == 0x7927);
    CHECK(half(out + 8) == 0x008B && half(out + 10) == 0x0889 && half(out + 12) == 0xF8E9);
    CHECK(half(out + 16) == 0x81FF && half(out + 22) == 0x3C00);  // (index 0 again; alpha 1.0)
    // Reserved headers (10011) decode to zero with alpha 1.
    BlockWriter r;
    r.put(0x13, 5);
    decodeBlock(Kind::BC6H, false, r.bytes, out);
    CHECK(half(out) == 0 && half(out + 2) == 0 && half(out + 4) == 0 && half(out + 6) == 0x3C00);
}

// A level whose size is not a multiple of 4: the blocks on the right and bottom contribute only the texels inside.
void edges() {
    // 6x5 texels = 2x2 BC1 blocks, each one flat: red, green / blue, white.
    const uint8_t red[8] = {0x00, 0xF8, 0x00, 0xF8, 0, 0, 0, 0}, green[8] = {0xE0, 0x07, 0xE0, 0x07, 0, 0, 0, 0};
    const uint8_t blue[8] = {0x1F, 0x00, 0x1F, 0x00, 0, 0, 0, 0}, white[8] = {0xFF, 0xFF, 0xFF, 0xFF, 0, 0, 0, 0};
    std::vector<uint8_t> src(16 + 16);
    std::memcpy(&src[0], red, 8), std::memcpy(&src[8], green, 8);
    std::memcpy(&src[16], blue, 8), std::memcpy(&src[24], white, 8);
    const size_t dstRow = 8 * 4;  // (wider than the 6 texels: the rest must stay untouched)
    std::vector<uint8_t> dst(dstRow * 6, 0xAA);
    decodeImage(Kind::BC1, false, src.data(), 16, 6, 5, dst.data(), dstRow);
    auto px = [&](unsigned x, unsigned y) { return &dst[y * dstRow + 4 * x]; };
    CHECK(px(0, 0)[0] == 255 && px(0, 0)[1] == 0);                  // red block
    CHECK(px(5, 0)[1] == 255 && px(5, 0)[0] == 0);                  // green block, its second column
    CHECK(px(3, 4)[2] == 255 && px(3, 4)[0] == 0);                  // blue block, last row
    CHECK(px(5, 4)[0] == 255 && px(5, 4)[1] == 255 && px(5, 4)[2] == 255);  // white block, one texel in
    CHECK(px(6, 0)[0] == 0xAA && px(7, 4)[3] == 0xAA);              // past the width
    CHECK(px(0, 5)[0] == 0xAA);                                     // past the height
    // A 1x1 level is one block.
    std::vector<uint8_t> one(4, 0xAA);
    decodeImage(Kind::BC1, false, red, 8, 1, 1, one.data(), 4);
    CHECK(one[0] == 255 && one[1] == 0 && one[2] == 0 && one[3] == 255);
}

void formats() {
    Kind k;
    CHECK(!kindOf(34, k) && !kindOf(42, k));
    for (uint8_t d = 35; d <= 41; ++d) CHECK(kindOf(d, k) && unsigned(k) == d - 35u);
    CHECK(hostFormat(Kind::BC1, false, false) == vpgpu::Format::RGBA8Unorm && hostFormat(Kind::BC7, true, false) == vpgpu::Format::RGBA8Srgb);
    CHECK(hostFormat(Kind::BC4, false, false) == vpgpu::Format::R8Unorm && hostFormat(Kind::BC4, false, true) == vpgpu::Format::R8Snorm);
    CHECK(hostFormat(Kind::BC5, false, true) == vpgpu::Format::RG8Snorm && hostFormat(Kind::BC6H, false, true) == vpgpu::Format::RGBA16Float);
    CHECK(layoutFormat(Kind::BC1, false, false) == vpgpu::Format::BC1 && layoutFormat(Kind::BC3, true, false) == vpgpu::Format::BC3Srgb);
    CHECK(layoutFormat(Kind::BC6H, false, true) == vpgpu::Format::BC6HSfloat && layoutFormat(Kind::BC5, false, false) == vpgpu::Format::BC5Unorm);
}

