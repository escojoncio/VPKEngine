#!/usr/bin/env python3
"""Generates src/f64_table.inc: 2/pi as a 1201-bit binary fraction (v_trig_preop_f64), 32 bits per word."""
import sys

BITS = 1201
P = BITS + 64  # working precision


def atan_inv(x, prec):
    one = 1 << prec
    term = one // x
    total = term
    x2 = x * x
    n = 1
    sign = -1
    while term:
        term //= x2
        n += 2
        total += sign * (term // n)
        sign = -sign
    return total


pi = 16 * atan_inv(5, P) - 4 * atan_inv(239, P)  # pi * 2^P
two_over_pi = (2 << (2 * P)) // pi  # 2/pi * 2^P
frac = two_over_pi >> (P - BITS)  # 2/pi * 2^1201, a 1201-bit integer
assert frac.bit_length() == BITS
words = (BITS + 31) // 32
frac <<= words * 32 - BITS
out = ["// Generated by tools/gen_two_over_pi.py: 2/pi as a %d-bit binary fraction, most significant word first." % BITS,
       "#define VPF_TWO_OVER_PI_WORDS %d" % words, "#define VPF_TWO_OVER_PI_DATA \\"]
for i in range(words):
    w = (frac >> (32 * (words - 1 - i))) & 0xFFFFFFFF
    out.append("    0x%08xu, %s" % (w, "\\" if i + 1 < words else ""))
open(sys.argv[1] if len(sys.argv) > 1 else "src/f64_table.inc", "w").write("\n".join(out) + "\n")
