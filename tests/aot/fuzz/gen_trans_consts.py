#!/usr/bin/env python3
"""Regenerates runtime/vp_x87_trans.h: the binary128 constants of the x87 transcendental functions and
pi/2 to 66 bits, with which the x87 reduces the argument of fsin/fcos/fptan.
    python3 gen_trans_consts.py > ../../../runtime/vp_x87_trans.h
Everything is computed with Python integers (Machin's formula for pi, a series for ln 2)."""
P = 1600  # fixed point bits


def arctan_inv(n):  # atan(1/n) * 2^P
    x = (1 << P) // n
    n2 = n * n
    s = x
    k = 1
    t = x
    while t:
        t //= n2
        k += 2
        s += -(t // k) if (k // 2) % 2 else (t // k)
    return s


def atan_inv(n):
    x = (1 << P) // n
    n2 = n * n
    total, term, k, sign = 0, x, 1, 1
    while term:
        total += sign * (term // k)
        term //= n2
        k += 2
        sign = -sign
    return total


PI = 4 * (4 * atan_inv(5) - atan_inv(239))


def ln_series(num, den):  # ln(num/den) * 2^P, as 2 atanh((num-den)/(num+den))
    z = ((num - den) << P) // (num + den)
    z2 = (z * z) >> P
    total, term, k = 0, z, 1
    while term:
        total += term // k
        term = (term * z2) >> P
        k += 2
    return 2 * total


LN2 = ln_series(2, 1)


def f128(value_fixed):
    """The binary128 (hi, lo) words of value_fixed / 2^P, rounded to nearest even."""
    v = value_fixed
    assert v > 0
    e = v.bit_length() - 1  # v = 2^e * 1.xxx
    sh = e - 112
    if sh > 0:
        q, r = v >> sh, v & ((1 << sh) - 1)
        half = 1 << (sh - 1)
        if r > half or (r == half and (q & 1)):
            q += 1
    else:
        q = v << -sh
    if q.bit_length() > 113:
        q >>= 1
        e += 1
    exp = e - P + 16383
    bits = (exp << 112) | (q & ((1 << 112) - 1))
    return bits >> 64, bits & ((1 << 64) - 1)


def words(name, fixed):
    hi, lo = f128(fixed)
    return f"#define {name} {{UINT64_C(0x{lo:016x}), UINT64_C(0x{hi:016x})}}"


print("""/* SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0
 *
 * Constants of the x87 transcendental functions (runtime/vp_x87.c): binary128 values as {low, high}
 * words. Generated by tests/aot/fuzz/gen_trans_consts.py. */
#ifndef VP_X87_TRANS_H
#define VP_X87_TRANS_H
""")
consts = {
    "VP_F128_PI": PI,
    "VP_F128_PI_2": PI >> 1,
    "VP_F128_PI_4": PI >> 2,
    "VP_F128_3PI_4": (PI * 3) >> 2,
    "VP_F128_LN2": LN2,
    "VP_F128_LOG2E": (1 << (2 * P)) // LN2,
    # pi/2 to 66 bits, the value the x87 reduces its argument with
    "VP_F128_PI_2_66": 0xC90FDAA22168C234C << (P - 67),
}
for k, v in consts.items():
    print(words(k, v))
print("\n#endif")
