/* Regenerates runtime/vp_rcp_tables.h from the RCPSS / RSQRTSS of the CPU it runs on (x86 only):
 *   cc -O2 -mavx gen_rcp_tables.c -o gen && ./gen > ../../../runtime/vp_rcp_tables.h
 * On Intel the result depends on the 11 (RCP) or 10 (RSQRT, one table per exponent parity) leading
 * mantissa bits only, and every table output is 0.5 <= x < 1 with 12 mantissa bits. */
#include <immintrin.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

static uint32_t hw(int rsqrt, uint32_t x) {
    float f, r;
    memcpy(&f, &x, 4);
    __m128 v = _mm_set_ss(f);
    v = rsqrt ? _mm_rsqrt_ss(v) : _mm_rcp_ss(v);
    r = _mm_cvtss_f32(v);
    memcpy(&x, &r, 4);
    return x;
}

int main(void) {
    printf("/* SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0\n *\n * RCPPS / RSQRTPS approximations (Intel): the 12 mantissa bits of a result in [0.5, 1), by the\n"
           " * leading mantissa bits of the operand. Generated by tests/aot/fuzz/gen_rcp_tables.c. */\n");
    printf("#ifndef VP_RCP_TABLES_H\n#define VP_RCP_TABLES_H\n#include <stdint.h>\n\n");
    printf("/* 1/x for x in [1, 2): index = the 11 leading mantissa bits. */\nstatic const uint16_t vp_rcp_table[2048] = {");
    for (uint32_t i = 0; i < 2048; ++i) printf("%s%s0x%03x,", i % 12 ? " " : "\n    ", "", (hw(0, (127u << 23) | (i << 12)) >> 11) & 0xfff);
    printf("\n};\n\n/* 1/sqrt(x): [0] for x in [1, 2), [1] for x in [2, 4); index = the 10 leading mantissa bits. */\nstatic const uint16_t vp_rsqrt_table[2][1024] = {");
    for (int p = 0; p < 2; ++p) {
        printf("{");
        for (uint32_t i = 0; i < 1024; ++i) printf("%s0x%03x,", i % 12 ? " " : "\n    ", (hw(1, ((127u + p) << 23) | (i << 13)) >> 11) & 0xfff);
        printf("\n}%s", p ? "" : ", ");
    }
    printf("};\n\n#endif\n");
    return 0;
}
