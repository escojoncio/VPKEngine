static inline void vp_push64(VpCpu* c, uint64_t v) {
    c->r[VP_RSP] -= 8;
    vp_st64(c->r[VP_RSP], v);
}
static inline uint64_t vp_pop64(VpCpu* c) {
    const uint64_t v = vp_ld64(c->r[VP_RSP]);
    c->r[VP_RSP] += 8;
    return v;
}

