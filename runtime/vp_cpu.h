/* RCPPS/RSQRTPS/RCPSS/RSQRTSS: the 12-bit approximations of the Intel CPUs, bit for bit, from the
 * tables above (vp_rcp_table, vp_rsqrt_table). A denormal operand counts as zero (infinity,
 * whatever DAZ says), a denormal result is zero, a NaN is quieted, and the square root of a
 * negative number is the indefinite. (AMD CPUs, Jaguar included, use other tables: only the Intel ones could be measured.)
 *
 * VP_RCP_MODEL (compile-time, for the translated code and the runtime alike) chooses the behaviour:
 *   VP_RCP_INTEL (default): the Intel tables. BEHAVIOUR CHANGE: before the tables the runtime computed 1/x and
 *     1/sqrt(x) exactly (single precision); the Intel values differ from those in the low 12 bits, so a guest
 *     that took the exact results now sees the 12-bit ones. They are what the hardware gives on Intel (all
 *     2^32 operands checked), not on the PS4's AMD Jaguar, whose tables were not measured and may differ.
 *   VP_RCP_EXACT: the former exact 1.0f / x and 1.0f / sqrtf(x). Build with -DVP_RCP_MODEL=VP_RCP_EXACT if a PS4
 *     guest depends on them (or on values nearer to Jaguar's, which also are not the Intel ones). */
#define VP_RCP_INTEL 0
#define VP_RCP_EXACT 1
#ifndef VP_RCP_MODEL
#define VP_RCP_MODEL VP_RCP_INTEL
#endif
static inline float vp_rcp_f32_intel(float f) {
    uint32_t x, o; memcpy(&x, &f, 4);
    const uint32_t s = x & 0x80000000u, e = (x >> 23) & 255, m = x & 0x7FFFFF;
    if (e == 255) o = m ? (x | 0x400000u) : s;
    else if (e == 0) o = s | 0x7F800000u;
    else {
        const int oe = 126 - ((int)e - 127);
        o = oe >= 255 ? (s | 0x7F800000u) : oe <= 0 ? s : (s | ((uint32_t)oe << 23) | ((uint32_t)vp_rcp_table[m >> 12] << 11));
    }
    float r; memcpy(&r, &o, 4); return r;
}
static inline float vp_rsqrt_f32_intel(float f) {
    uint32_t x, o; memcpy(&x, &f, 4);
    const uint32_t s = x & 0x80000000u, e = (x >> 23) & 255, m = x & 0x7FFFFF;
    if (e == 255) o = m ? (x | 0x400000u) : s ? 0xFFC00000u : 0;
    else if (e == 0) o = s | 0x7F800000u;
    else if (s) o = 0xFFC00000u;
    else {
        const int k = (int)e - 127, h = k >> 1; /* floor(k / 2) */
        const int oe = 126 - h;
        o = oe >= 255 ? 0x7F800000u : oe <= 0 ? 0 : (((uint32_t)oe << 23) | ((uint32_t)vp_rsqrt_table[k & 1][m >> 13] << 11));
    }
    float r; memcpy(&r, &o, 4); return r;
}
static inline float vp_rcp_f32(float f) {
#if VP_RCP_MODEL == VP_RCP_EXACT
    return 1.0f / f;
#else
    return vp_rcp_f32_intel(f);
#endif
}
static inline float vp_rsqrt_f32(float f) {
#if VP_RCP_MODEL == VP_RCP_EXACT
    return 1.0f / sqrtf(f);
#else
    return vp_rsqrt_f32_intel(f);
#endif
}

