#!/usr/bin/env python3
"""Generates the C source of the EGL/GLES shim for the dEQP GLES run on macOS (CI).

  gen_shim.py <include dir with EGL/egl.h and GLES2/gl2.h, GLES3/gl3.h, gl31.h, gl32.h> <out.c>

The shim exports every core egl* and gl* name of the Khronos headers. Each one is a 4-instruction arm64 trampoline
(adrp/add/ldr/br through a table, argument registers and stack untouched) to the function vpgles_proc() returns for the same
name, so the shim never needs the real signatures. The table is filled when the dylib loads: it dlopens the VPVulkan
dylib named by VPGLES_VULKAN_LIB (default libVPVulkan.dylib) and calls vpgles_init(vkGetInstanceProcAddr). A name vpgles
does not have jumps to a stub that logs it ("vpgles-shim: unimplemented glFoo") and returns 0.

Darwin packs narrow stack arguments, vpgles reads 8-byte slots for the ones past the eighth (gl_api.cpp, `S`): the
functions where that differs (the ones with two integer arguments on the stack) are C wrappers here.
eglGetProcAddress is C too: it returns the shim's own entry points (so those wrappers are used), then whatever
vpgles_proc knows (extensions), never a function vpgles lacks for a core name.
"""
import re, sys

# Functions whose stack arguments differ between the Darwin caller and vpgles (see above): C wrappers, hand typed.
# name -> (C return, [C parameter types] as the GL header declares them, [types vpgles reads])
I = "int"
U = "unsigned"
S = "long long"
WRAPPERS = {
    "glTexSubImage3D": ([U, I, I, I, I, I, I, I, U, U, "const void*"], [U, I, I, I, I, I, I, I, S, S, "const void*"]),
    "glCompressedTexSubImage3D": ([U, I, I, I, I, I, I, I, U, I, "const void*"], [U, I, I, I, I, I, I, I, S, S, S]),
    "glBlitFramebuffer": ([I, I, I, I, I, I, I, I, U, U], [I, I, I, I, I, I, I, I, S, S]),
}


def names(inc, files, api):
    found = set()
    rx = re.compile(r"\b%s\b[^;(]*?\b(\w+)\s*\(" % api)
    for f in files:
        txt = open(f"{inc}/{f}", errors="replace").read()
        txt = re.sub(r"/\*.*?\*/", "", txt, flags=re.S)
        for line in txt.splitlines():
            m = rx.search(line)
            if m and m.group(1).startswith(("gl", "egl")):
                found.add(m.group(1))
    return found


def main():
    inc, out = sys.argv[1], sys.argv[2]
    gl = names(inc, ["GLES2/gl2.h", "GLES3/gl3.h", "GLES3/gl31.h", "GLES3/gl32.h"], "GL_APICALL")
    egl = names(inc, ["EGL/egl.h"], "EGLAPI")
    gl = {n for n in gl if n.startswith("gl")}
    egl = {n for n in egl if n.startswith("egl")}
    if len(gl) < 200 or len(egl) < 30:
        sys.exit(f"gen_shim: too few names (gl {len(gl)}, egl {len(egl)}): header format changed?")
    allnames = sorted(gl | egl)
    allnames = [n for n in allnames if n != "eglGetProcAddress"]
    idx = {n: i for i, n in enumerate(allnames)}
    w = []
    w.append("// Generated by gen_shim.py. Do not edit.\n#include <dlfcn.h>\n#include <stdio.h>\n#include <stdlib.h>\n"
             "#include <string.h>\n\n#define N %d\n" % len(allnames))
    w.append("static const char* const kNames[N] = {\n" + ",\n".join(f'    "{n}"' for n in allnames) + "};\n")
    w.append("__attribute__((visibility(\"hidden\"), used)) void* vps_tab[N];\n"
             "extern void vps_unimpl(void) __attribute__((visibility(\"hidden\")));\n"
             "__attribute__((visibility(\"hidden\"), used)) void vps_unimpl_log(unsigned long i) {\n"
             "    static unsigned char seen[N];\n"
             "    if (i < N && !seen[i]) { seen[i] = 1; fprintf(stderr, \"vpgles-shim: unimplemented %s\\n\", kNames[i]); }\n"
             "    else if (i >= N) fprintf(stderr, \"vpgles-shim: unimplemented (slot unknown)\\n\");\n}\n")
    w.append('__asm__(".text\\n.p2align 2\\n.globl _vps_unimpl\\n.private_extern _vps_unimpl\\n_vps_unimpl:\\n"\n'
             '        "stp x29, x30, [sp, #-16]!\\nmov x0, x17\\nbl _vps_unimpl_log\\nldp x29, x30, [sp], #16\\nmov x0, #0\\nret\\n");\n')
    w.append('#define T(name, idx, off) __asm__(".text\\n.p2align 2\\n.globl _" #name "\\n_" #name ":\\n"'
             ' "adrp x16, _vps_tab@PAGE\\nadd x16, x16, _vps_tab@PAGEOFF\\nldr x16, [x16, #" #off "]\\n"'
             ' "mov x17, #" #idx "\\nbr x16\\n");\n')
    # wrappers
    for n, (hdr, real) in WRAPPERS.items():
        i = idx[n]
        params = ", ".join(f"{t} a{k}" for k, t in enumerate(hdr))
        args = ", ".join(f"({real[k]})a{k}" if real[k] == S and hdr[k] != "const void*" else f"a{k}"
                         for k in range(len(hdr)))
        if real[-1] == S and hdr[-1] == "const void*":
            args = args.rsplit(", ", 1)[0] + f", (long long)(__INTPTR_TYPE__)a{len(hdr) - 1}"
        w.append(f"__attribute__((visibility(\"default\"))) void {n}({params}) {{\n"
                 f"    void* f = vps_tab[{i}];\n    if (f == (void*)vps_unimpl) {{ vps_unimpl_log({i}); return; }}\n"
                 f"    ((void (*)({', '.join(real)}))f)({args});\n}}\n")
    w.append("// trampolines")
    for n in allnames:
        if n in WRAPPERS:
            continue
        w.append(f"T({n}, {idx[n]}, {idx[n] * 8})")
    w.append("\n" + "\n".join(f"extern void {n}(void);" for n in allnames if n not in WRAPPERS))
    w.append("static void* const kExports[N] = {\n" + ",\n".join(f"    (void*){n}" for n in allnames) + "};\n")
    w.append(r'''
static void* (*pProc)(const char*);

__attribute__((constructor)) static void vps_load(void) {
    for (unsigned i = 0; i < N; ++i) vps_tab[i] = (void*)vps_unimpl;
    const char* path = getenv("VPGLES_VULKAN_LIB");
    void* lib = dlopen(path && *path ? path : "libVPVulkan.dylib", RTLD_NOW | RTLD_LOCAL);
    if (!lib) { fprintf(stderr, "vpgles-shim: cannot load the Vulkan driver (%s): %s\n", path ? path : "libVPVulkan.dylib", dlerror()); return; }
    int (*init)(void*) = (int (*)(void*))dlsym(lib, "vpgles_init");
    pProc = (void* (*)(const char*))dlsym(lib, "vpgles_proc");
    void* gipa = dlsym(lib, "vkGetInstanceProcAddr");
    if (!init || !pProc || !gipa) { fprintf(stderr, "vpgles-shim: vpgles_init/vpgles_proc/vkGetInstanceProcAddr missing in the driver\n"); pProc = 0; return; }
    if (!init(gipa)) { fprintf(stderr, "vpgles-shim: vpgles_init failed\n"); pProc = 0; return; }
    unsigned have = 0;
    for (unsigned i = 0; i < N; ++i) {
        void* p = pProc(kNames[i]);
        if (p) { vps_tab[i] = p; ++have; }
    }
    fprintf(stderr, "vpgles-shim: %u of %u core entry points resolved\n", have, (unsigned)N);
}

static int hasSuffix(const char* s, const char* suf) {
    size_t a = strlen(s), b = strlen(suf);
    return a > b && !strcmp(s + a - b, suf);
}

__attribute__((visibility("default"))) void* eglGetProcAddress(const char* name) {
    if (!name) return 0;
    if (!strcmp(name, "eglGetProcAddress")) return (void*)eglGetProcAddress;
    for (unsigned i = 0; i < N; ++i)
        if (!strcmp(kNames[i], name)) return vps_tab[i] == (void*)vps_unimpl ? 0 : kExports[i];
    static const char* const suf[] = {"OES", "EXT", "KHR", "ANGLE", "NV", "ARB", "IMG", "APPLE", "QCOM"};
    for (unsigned s = 0; s < sizeof suf / sizeof suf[0]; ++s) {
        if (!hasSuffix(name, suf[s])) continue;
        char base[256];
        size_t len = strlen(name) - strlen(suf[s]);
        if (len >= sizeof base) break;
        memcpy(base, name, len);
        base[len] = 0;
        for (unsigned i = 0; i < N; ++i)
            if (!strcmp(kNames[i], base)) return vps_tab[i] == (void*)vps_unimpl ? 0 : kExports[i];
    }
    return pProc ? pProc(name) : 0;
}
''')
    open(out, "w").write("\n".join(w))
    print(f"gen_shim: {len(gl)} gl + {len(egl)} egl names, {len(WRAPPERS)} wrappers")


if __name__ == "__main__":
    main()
